export function translatePattern(text: string, translate: (value: string) => string): string | null {
  const count = text.match(/^(\d+)\s+([A-Za-z][A-Za-z -]*?)$/);
  if (count) {
    const [, value, unit] = count;
    const normalized = unit.toLowerCase();
    return `${value} ${countWords[normalized] || translate(unit)}`;
  }

  const activeCounts = text.match(/^(\d+)\s+active\s+·\s+(\d+)\s+inbox\s+·\s+(\d+)\s+outbox\s+·\s+(\d+)\s+DLQ$/);
  if (activeCounts) return `${activeCounts[1]} 活跃 · ${activeCounts[2]} 入站 · ${activeCounts[3]} 出站 · ${activeCounts[4]} 死信`;

  const completed = text.match(/^(.+)\s+completed$/);
  if (completed) return `${translate(completed[1])} 已完成`;

  const failed = text.match(/^(.+)\s+failed$/);
  if (failed) return `${translate(failed[1])} 失败`;

  const endpoint = text.match(/^Endpoint:\s+(.+)$/);
  if (endpoint) return `端点：${endpoint[1]}`;

  const approvalSaved = text.match(/^Approval saved at\s+(.+)$/);
  if (approvalSaved) return `审批策略已保存于 ${approvalSaved[1]}`;

  const contextValue = text.match(/^Context\s+(.+)$/);
  if (contextValue) return `上下文 ${translate(contextValue[1])}`;

  const sources = text.match(/^(\d+)\s+sources$/);
  if (sources) return `${sources[1]} 个来源`;

  const iterations = text.match(/^(\d+)\s+iterations$/);
  if (iterations) return `${iterations[1]} 轮迭代`;

  const keep = text.match(/^Keep\s+(.+)$/);
  if (keep) return `保留 ${translate(keep[1])}`;

  const command = text.match(/^Command\s+(.+)$/);
  if (command) return `命令 ${command[1]}`;

  const rename = text.match(/^Rename\s+(.+)$/);
  if (rename) return `重命名 ${rename[1]}`;

  const del = text.match(/^Delete\s+(.+)$/);
  if (del) return `删除 ${del[1]}`;

  return null;
}
