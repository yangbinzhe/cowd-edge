import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const root = path.resolve(import.meta.dirname, '..')
const contractPath = path.join(root, 'contracts', 'driver-profiles.json')
const contract = JSON.parse(fs.readFileSync(contractPath, 'utf8'))
const version = fs
  .readFileSync(path.join(root, 'Cargo.toml'), 'utf8')
  .match(/\[workspace\.package\][\s\S]*?version\s*=\s*"([^"]+)"/)?.[1]

if (!version) throw new Error('workspace version not found')
if (contract.schema !== 'cowd.edge.driver-profiles.v1') throw new Error('invalid driver profile schema')

const ids = new Set()
const paths = new Set()
const artifacts = new Set()
const resolved = contract.profiles.map((profile) => {
  const template = profile.template ? contract.templates[profile.template] : {}
  const value = {...template, ...profile}
  if (!value.id || ids.has(value.id)) throw new Error(`duplicate or empty profile id: ${value.id}`)
  if (!value.path || paths.has(value.path)) throw new Error(`duplicate or empty manifest path: ${value.path}`)
  if (!/^[a-z0-9][a-z0-9-]*$/.test(value.artifact)) throw new Error(`unsafe artifact: ${value.artifact}`)
  ids.add(value.id)
  paths.add(value.path)
  artifacts.add(value.artifact)
  return value
})

function manifest(profile) {
  return {
    schema: 'cowd.surface.v1',
    id: profile.surface_id,
    name: profile.name,
    version,
    kind: profile.kind,
    runtime: {
      kind: 'managed',
      artifact: profile.artifact,
      driver_profile: profile.id,
      transport: 'uds-http2',
    },
    capabilities: profile.capabilities,
    routes: profile.routes ?? [],
    resources: [],
    health: {mode: 'http2', interval_ms: 30000, timeout_ms: 5000},
    config_schema: profile.config_schema ?? null,
    default_enabled: false,
  }
}

function rustString(value) {
  return JSON.stringify(value ?? '')
}

function rustSlice(values) {
  return `&[${values.map(rustString).join(', ')}]`
}

const generatedRust = `// @generated by scripts/generate-driver-profiles.mjs; do not edit.\n\
#[derive(Debug, Clone, Copy)]\n\
pub struct DriverProfile {\n\
    pub id: &'static str,\n\
    pub surface_id: &'static str,\n\
    pub artifact: &'static str,\n\
    pub adapter_id: &'static str,\n\
    pub default_base_url: &'static str,\n\
    pub capabilities: &'static [&'static str],\n\
}\n\n\
pub const DRIVER_PROFILES: &[DriverProfile] = &[\n${resolved.map((profile) => `    DriverProfile { id: ${rustString(profile.id)}, surface_id: ${rustString(profile.surface_id)}, artifact: ${rustString(profile.artifact)}, adapter_id: ${rustString(profile.adapter_id)}, default_base_url: ${rustString(profile.default_base_url)}, capabilities: ${rustSlice(profile.capabilities)} },`).join('\n')}\n];\n\n\
pub fn driver_profile(id: &str) -> Option<&'static DriverProfile> {\n\
    DRIVER_PROFILES.iter().find(|profile| profile.id == id)\n\
}\n`

const outputs = new Map([
  ...resolved.map((profile) => [path.join(root, profile.path), `${JSON.stringify(manifest(profile), null, 2)}\n`]),
  [path.join(root, 'crates', 'edge-adapters', 'src', 'driver_profiles_generated.rs'), generatedRust],
])

const check = process.argv.includes('--check')
const mismatches = []
for (const [file, content] of outputs) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) mismatches.push(path.relative(root, file))
  } else {
    fs.mkdirSync(path.dirname(file), {recursive: true})
    fs.writeFileSync(file, content)
  }
}

if (mismatches.length) {
  console.error(`driver profile generated outputs are stale:\n${mismatches.join('\n')}`)
  process.exit(1)
}

console.log(check ? `driver profile gate passed (${outputs.size} outputs)` : `generated ${outputs.size} driver profile outputs`)
